        "relative flex w-full cursor-pointer items-center justify-between gap-3 rounded-[6px] px-3 py-1.5 text-[13px] outline-none select-none transition-colors hover:bg-[#151515]/4 focus:bg-[#151515]/4 data-[state=checked]:bg-[#3b82f6]/8 data-[state=checked]:font-semibold data-[state=checked]:text-[#3b82f6] text-[#151515] data-disabled:pointer-events-none data-disabled:opacity-50",
